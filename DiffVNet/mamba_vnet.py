class LayerNorm(nn.Module):
    r""" LayerNorm that supports two data formats: channels_last (default) or channels_first.
    The ordering of the dimensions in the inputs. channels_last corresponds to inputs with
    shape (batch_size, height, width, channels) while channels_first corresponds to inputs
    with shape (batch_size, channels, height, width).
    """
    def __init__(self, normalized_shape, eps=1e-6, data_format="channels_last"):
        super().__init__()
        self.weight = nn.Parameter(torch.ones(normalized_shape))
        self.bias = nn.Parameter(torch.zeros(normalized_shape))
        self.eps = eps
        self.data_format = data_format
        if self.data_format not in ["channels_last", "channels_first"]:
            raise NotImplementedError
        self.normalized_shape = (normalized_shape, )

    def forward(self, x):
        if self.data_format == "channels_last":
            return F.layer_norm(x, self.normalized_shape, self.weight, self.bias, self.eps)
        elif self.data_format == "channels_first":
            u = x.mean(1, keepdim=True)
            s = (x - u).pow(2).mean(1, keepdim=True)
            x = (x - u) / torch.sqrt(s + self.eps)
            x = self.weight[:, None, None, None] * x + self.bias[:, None, None, None]

            return x
                
class MambaLayer(nn.Module):
    def __init__(self, dim=16, d_state = 16, d_conv = 4, expand = 2, num_slices=5):
        super().__init__()
        self.dim = dim
        self.norm = nn.LayerNorm(dim)
        self.mamba = Mamba(
                d_model=dim, # Model dimension d_model
                d_state=d_state,  # SSM state expansion factor
                d_conv=d_conv,    # Local convolution width
                expand=expand,    # Block expansion factor
                bimamba_type="v3",
                nslices=num_slices,
        )
    
    def forward(self, x):
        B, C = x.shape[:2]
        assert C == self.dim
        n_tokens = x.shape[2:].numel()
        img_dims = x.shape[2:]
        x_flat = x.reshape(B, C, n_tokens).transpose(-1, -2)
        x_norm = self.norm(x_flat)
        
        x_mamba = self.mamba(x_norm)

        out = x_mamba.transpose(-1, -2).reshape(B, C, *img_dims)
        return out
        
# Frequency 
class fftshift(nn.Module):
    def __init__(self, dim=None):
        super(fftshift, self).__init__()
        
        self.dim = dim
    
    def forward(self, x):
        if self.dim is None:
            self.dim = tuple(range(x.dim()))
        shift = tuple(s // 2 for s in x.shape[2:5])
        return torch.roll(x, shift, dims=self.dim).cuda()
    
class Bandfilter(nn.Module):
    def __init__(self, high_threshold):
        super(Bandfilter, self).__init__()
        
        self.high_threshold = high_threshold

    def forward(self, x):
        high_filter = (torch.abs(x) > self.high_threshold)
        high_freq_image = x * high_filter
        return high_freq_image
        
class FreMambaLayer(nn.Module):
    def __init__(self, dim=16, d_state = 16, d_conv = 4, expand = 2, num_slices=6): # 5
        super().__init__()
        self.dim = dim
        self.norm = nn.LayerNorm(dim)
        self.mamba = Mamba(
                d_model=dim, # Model dimension d_model
                d_state=d_state,  # SSM state expansion factor
                d_conv=d_conv,    # Local convolution width
                expand=expand,    # Block expansion factor
                bimamba_type="v3",
                nslices=num_slices,
        )
        
        self.fftshift = fftshift(dim=(2,3,4))
        self.Bandfilter = Bandfilter(0.6)
        self.weight = nn.Parameter(torch.ones(1, 1, 6,6,6)) #7,7,5))
    
    def forward(self, x):
        B, C = x.shape[:2]
        assert C == self.dim
        n_tokens = x.shape[2:].numel()
        img_dims = x.shape[2:]
        
        fx = fft.fftn(x.float(), dim=(2,3,4))
        fx = self.fftshift(fx)
        fx = fx.to(device=torch.device('cuda'), dtype=torch.float32)
        hfx = self.Bandfilter(fx)
        hx = fft.ifftn(hfx)
        hx = hx.to(device=torch.device('cuda'), dtype=torch.float32)
        
        hx_flat = hx.reshape(B, C, n_tokens).transpose(-1, -2)
        hx_norm = self.norm(hx_flat)
        
        x_mamba = self.mamba(hx_norm)

        out = x_mamba.transpose(-1, -2).reshape(B, C, *img_dims)
        out = self.weight*out
        return out
    
    
class MlpChannel(nn.Module):
    def __init__(self,hidden_size, mlp_dim, ):
        super().__init__()
        self.fc1 = nn.Conv3d(hidden_size, mlp_dim, 1)
        self.act = nn.GELU()
        self.fc2 = nn.Conv3d(mlp_dim, hidden_size, 1)

    def forward(self, x):
        x = self.fc1(x)
        x = self.act(x)
        x = self.fc2(x)
        return x

class GSC(nn.Module):
    def __init__(self, in_channles) -> None:
        super().__init__()

        self.proj = nn.Conv3d(in_channles, in_channles, 3, 1, 1)
        self.norm = nn.InstanceNorm3d(in_channles)
        self.nonliner = nn.ReLU()

        self.proj2 = nn.Conv3d(in_channles, in_channles, 3, 1, 1)
        self.norm2 = nn.InstanceNorm3d(in_channles)
        self.nonliner2 = nn.ReLU()

        self.proj3 = nn.Conv3d(in_channles, in_channles, 1, 1, 0)
        self.norm3 = nn.InstanceNorm3d(in_channles)
        self.nonliner3 = nn.ReLU()

        self.proj4 = nn.Conv3d(in_channles, in_channles, 1, 1, 0)
        self.norm4 = nn.InstanceNorm3d(in_channles)
        self.nonliner4 = nn.ReLU()

    def forward(self, x):

        x_residual = x 

        x1 = self.proj(x)
        x1 = self.norm(x1)
        x1 = self.nonliner(x1)

        x1 = self.proj2(x1)
        x1 = self.norm2(x1)
        x1 = self.nonliner2(x1)

        x2 = self.proj3(x)
        x2 = self.norm3(x2)
        x2 = self.nonliner3(x2)

        x = x1 + x2
        x = self.proj4(x)
        x = self.norm4(x)
        x = self.nonliner4(x)
        
        return x + x_residual

class MambaBlock(nn.Module):
    def __init__(self, in_chans=1, depths=2, dims=32, num_slices = 32, drop_path_rate=0., layer_scale_init_value=1e-6):
        super().__init__()
        
        self.gsc = GSC(dims)

        self.stage = nn.Sequential(*[FreMambaLayer(dim=dims, d_state = num_slices) for j in range(1)])

        self.layer = nn.InstanceNorm3d(dims)
        self.mlp = MlpChannel(dims, 2 * dims)

    def forward(self, x):
        x = self.gsc(x)
        #print("1:",x)
        x = self.stage(x)
        x_out = self.layer(x)
        x_out = self.mlp(x_out)

        return x_out

class VNet(nn.Module):
    def __init__(self, n_channels=3, depths=2, drop_path_rate=0, layer_scale_init_value=1e-6, n_classes=2, n_filters=32, normalization='none', has_dropout=False, feat_dim=8):
        super(VNet, self).__init__()
        self.has_dropout = has_dropout

        self.block_one = ConvBlock(1, n_channels, n_filters, normalization=normalization)
        self.block_one_dw = DownsamplingConvBlock(n_filters, 2 * n_filters, normalization=normalization)

        self.block_two = ConvBlock(2, n_filters * 2, n_filters * 2, normalization=normalization)
        self.block_two_dw = DownsamplingConvBlock(n_filters * 2, n_filters * 4, normalization=normalization)

        self.block_three = ConvBlock(3, n_filters * 4, n_filters * 4, normalization=normalization)
        self.block_three_dw = DownsamplingConvBlock(n_filters * 4, n_filters * 8, normalization=normalization)

        self.block_four = ConvBlock(3, n_filters * 8, n_filters * 8, normalization=normalization)
        self.block_four_dw = DownsamplingConvBlock(n_filters * 8, n_filters * 16, normalization=normalization)

        self.block_five = ConvBlock(3, n_filters * 16, n_filters * 16, normalization=normalization)
        self.mamba = MambaBlock(n_filters * 16, depths=depths, dims=n_filters*16, num_slices=8, drop_path_rate=drop_path_rate, layer_scale_init_value=layer_scale_init_value)
        self.block_five_up = UpsamplingDeconvBlock(n_filters * 16, n_filters * 8, normalization=normalization)

        self.block_six = ConvBlock(3, n_filters * 8, n_filters * 8, normalization=normalization)
        self.block_six_up = UpsamplingDeconvBlock(n_filters * 8, n_filters * 4, normalization=normalization)

        self.block_seven = ConvBlock(3, n_filters * 4, n_filters * 4, normalization=normalization)
        self.block_seven_up = UpsamplingDeconvBlock(n_filters * 4, n_filters * 2, normalization=normalization)

        self.block_eight = ConvBlock(2, n_filters * 2, n_filters * 2, normalization=normalization)
        self.block_eight_up = UpsamplingDeconvBlock(n_filters * 2, n_filters, normalization=normalization)

        self.block_nine = ConvBlock(1, n_filters, n_filters, normalization=normalization)
        self.out_conv = nn.Conv3d(n_filters, n_classes, 1, padding=0)

        self.dropout = nn.Dropout3d(p=0.5, inplace=False)
        # self.__init_weight()
        
        self.projection_head = nn.Sequential(
            nn.Linear(n_filters, feat_dim),
            nn.BatchNorm1d(feat_dim),
            nn.ReLU(inplace=True),
            nn.Linear(feat_dim, feat_dim)
        )
        
    def encoder(self, input):
        x1 = self.block_one(input)
        x1_dw = self.block_one_dw(x1)

        x2 = self.block_two(x1_dw)
        x2_dw = self.block_two_dw(x2)

        x3 = self.block_three(x2_dw)
        x3_dw = self.block_three_dw(x3)

        x4 = self.block_four(x3_dw)
        x4_dw = self.block_four_dw(x4)

        x5 = self.block_five(x4_dw)
        x5_m = self.mamba(x5)
        x5 = x5 + x5_m
       
        if self.has_dropout:
            x5 = self.dropout(x5)

        res = [x1, x2, x3, x4, x5]

        return res

    def decoder(self, features):
        x1 = features[0]
        x2 = features[1]
        x3 = features[2]
        x4 = features[3]
        x5 = features[4]

        x5_up = self.block_five_up(x5)
        x5_up = x5_up + x4

        x6 = self.block_six(x5_up)
        x6_up = self.block_six_up(x6)
        x6_up = x6_up + x3

        x7 = self.block_seven(x6_up)
        x7_up = self.block_seven_up(x7)
        x7_up = x7_up + x2

        x8 = self.block_eight(x7_up)
        x8_up = self.block_eight_up(x8)
        x8_up = x8_up + x1
        x9 = self.block_nine(x8_up)
        if self.has_dropout:
            x9 = self.dropout(x9)
        out = self.out_conv(x9)
        return out, x9

    def forward(self, input, turnoff_drop=False):
        if turnoff_drop:
            has_dropout = self.has_dropout
            self.has_dropout = False
        features = self.encoder(input)
        self.featuremap_center = features[-1].detach()
        out = self.decoder(features)
        if turnoff_drop:
            self.has_dropout = has_dropout
        return out


def Dropout(x, p=0.5):
    x = torch.nn.functional.dropout(x, p)
    return x


def FeatureNoise(x, noise_range=0.3):
    noise = torch.clamp(torch.randn_like(x) * 0.1, -noise_range, noise_range)
    x = x + noise
    return x


